ALTER TABLE clients DROP CONSTRAINT IF EXISTS chk_clients_correo_formato;
ALTER TABLE clients
    ADD CONSTRAINT chk_clients_intentos_fallidos
        CHECK (intentos_fallidos >= 0),
    ADD CONSTRAINT chk_clients_correo_formato
        CHECK (correo_electronico = lower(trim(correo_electronico)));


-- Manejo de ROLES: tabla que administra admin y user segun dominio de correo.
CREATE TABLE IF NOT EXISTS profiles_rols (
    id_rol SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(10) NOT NULL UNIQUE,
    nombre VARCHAR(30) NOT NULL UNIQUE,
    CONSTRAINT chk_profiles_rols_codigo
        CHECK (codigo IN ('ADMIN', 'USER'))
);
