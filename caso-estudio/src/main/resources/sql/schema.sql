-- Compatibilidad y restricciones de tablas de negocio
ALTER TABLE books DROP CONSTRAINT IF EXISTS chk_books_precio_no_negativo;
ALTER TABLE books DROP CONSTRAINT IF EXISTS chk_books_inventario_no_negativo;
ALTER TABLE books DROP CONSTRAINT IF EXISTS chk_books_paginas_positivas;
ALTER TABLE books DROP CONSTRAINT IF EXISTS chk_books_anio_valido;
ALTER TABLE books
    ADD CONSTRAINT chk_books_precio_no_negativo CHECK (precio_venta >= 0),
    ADD CONSTRAINT chk_books_inventario_no_negativo CHECK (cantidad_inventario >= 0),
    ADD CONSTRAINT chk_books_paginas_positivas
        CHECK (numero_paginas IS NULL OR numero_paginas > 0),
    ADD CONSTRAINT chk_books_anio_valido
        CHECK (anio_publicacion IS NULL OR anio_publicacion BETWEEN 1 AND 9999);

ALTER TABLE buys DROP CONSTRAINT IF EXISTS chk_buys_totales_no_negativos;
ALTER TABLE buys
    ADD CONSTRAINT chk_buys_totales_no_negativos
        CHECK (
            (total_impuestos IS NULL OR total_impuestos >= 0) AND
            (subtotal IS NULL OR subtotal >= 0) AND
            (total_pagar IS NULL OR total_pagar >= 0)
        );

