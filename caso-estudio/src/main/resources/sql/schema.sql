INSERT INTO profiles_rols (codigo, nombre)
VALUES ('ADMIN', 'Administrador'), ('USER', 'Usuario')
ON CONFLICT (codigo) DO NOTHING;

ALTER TABLE clients DROP CONSTRAINT IF EXISTS fk_clients_rol;
ALTER TABLE clients
    ADD CONSTRAINT fk_clients_rol
    FOREIGN KEY (rol_id) REFERENCES profiles_rols(id_rol);

