    ADD COLUMN IF NOT EXISTS tipo_identificacion VARCHAR(20),
    ADD COLUMN IF NOT EXISTS identificacion VARCHAR(30),
    ADD COLUMN IF NOT EXISTS contrasenia_hash TEXT,
    ADD COLUMN IF NOT EXISTS fecha_registro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
