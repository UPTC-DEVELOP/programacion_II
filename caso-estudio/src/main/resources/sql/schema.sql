BEGIN;

-- CLIENTES: albergara usuarios remium y regulares segun sus compras en el aplicativo
CREATE TABLE IF NOT EXISTS clients (
    id_cliente SERIAL PRIMARY KEY,
    nombre_completo VARCHAR(150) NOT NULL,
    correo_electronico VARCHAR(100) UNIQUE NOT NULL,
    direccion_envio TEXT,
    telefono_contacto VARCHAR(20),
    tipo_cliente VARCHAR(20) CHECK (tipo_cliente IN ('Regular', 'Premium')) NOT NULL
);

-- LIBROS: albergara libros que se colocan desde el admin dashboard.
CREATE TABLE IF NOT EXISTS books (
    isbn VARCHAR(20) PRIMARY KEY,
    titulo VARCHAR(200) NOT NULL,
    autores VARCHAR(200) NOT NULL,
    anio_publicacion INT,
    categoria VARCHAR(100),
    editorial VARCHAR(100),
    numero_paginas INT,
    precio_venta DECIMAL(10, 2) NOT NULL,
    porcentaje_iva INT CHECK (porcentaje_iva IN (5, 19)) NOT NULL,
    cantidad_inventario INT DEFAULT 0,
    formato VARCHAR(20) CHECK (formato IN ('Físico', 'Digital')) NOT NULL
);

-- VENTAS: alberga ventas realizadas en caso de factura para usuarios.
CREATE TABLE IF NOT EXISTS buys (
    id_venta SERIAL PRIMARY KEY,
    id_cliente INT REFERENCES clients(id_cliente),
    fecha_compra TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    total_impuestos DECIMAL(10, 2),
    subtotal DECIMAL(10, 2),
    total_pagar DECIMAL(10, 2),
    metodo_pago VARCHAR(50)
);

-- DETALLES DE LAS VENTAS: detalles de las ventas segun la cantidad y demas.
CREATE TABLE IF NOT EXISTS sale_detais (
    id_detalle SERIAL PRIMARY KEY,
    id_venta INT REFERENCES buys(id_venta) ON DELETE CASCADE,
    isbn_libro VARCHAR(20) REFERENCES books(isbn),
    cantidad INT NOT NULL,
    precio_unitario DECIMAL(10, 2),
    subtotal DECIMAL(10, 2)
);

-- RESEÑAS DE LOS LIBROS (RF19 y RF20): reseñas segun DAD del grupo 7.
CREATE TABLE IF NOT EXISTS product_reviews (
    id_resena SERIAL PRIMARY KEY,
    isbn_libro VARCHAR(20) REFERENCES books(isbn),
    id_cliente INT REFERENCES clients(id_cliente),
    calificacion INT CHECK (calificacion BETWEEN 1 AND 5),
    comentario TEXT,
    fecha TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- CARRITO DE COMPRAS (Soporte para RF10, RF11, RF12, RF17): carrito de compras persistencia en postgreSQL
CREATE TABLE IF NOT EXISTS shopping_carts (
    id_carrito SERIAL PRIMARY KEY,
    id_cliente INT REFERENCES clients(id_cliente) ON DELETE CASCADE UNIQUE,
    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
-- ITEMS DE CARRITO:guarda info en caso de factura segun lo que se realize en el carrito, incremento o decremento de cantidad
CREATE TABLE IF NOT EXISTS cart_items (
    id_item SERIAL PRIMARY KEY,
    id_carrito INT REFERENCES shopping_carts(id_carrito) ON DELETE CASCADE,
    isbn_libro VARCHAR(20) REFERENCES books(isbn) ON DELETE CASCADE,
    cantidad INT NOT NULL CHECK (cantidad > 0),
    precio_unitario DECIMAL(10, 2) NOT NULL,
    subtotal DECIMAL(10, 2) NOT NULL,
    CONSTRAINT uq_carrito_libro UNIQUE (id_carrito, isbn_libro)
);


