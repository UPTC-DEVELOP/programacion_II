ALTER TABLE sale_detais DROP CONSTRAINT IF EXISTS chk_sale_detais_cantidad;
ALTER TABLE sale_detais DROP CONSTRAINT IF EXISTS chk_sale_detais_precio_no_negativo;
ALTER TABLE sale_detais DROP CONSTRAINT IF EXISTS chk_sale_detais_subtotal_no_negativo;
ALTER TABLE sale_detais
    ADD CONSTRAINT chk_sale_detais_cantidad CHECK (cantidad > 0),
    ADD CONSTRAINT chk_sale_detais_precio_no_negativo
        CHECK (precio_unitario IS NULL OR precio_unitario >= 0),
    ADD CONSTRAINT chk_sale_detais_subtotal_no_negativo
        CHECK (subtotal IS NULL OR subtotal >= 0);

ALTER TABLE product_reviews DROP CONSTRAINT IF EXISTS uq_product_reviews_cliente_libro;
ALTER TABLE product_reviews
    ADD CONSTRAINT uq_product_reviews_cliente_libro
        UNIQUE (isbn_libro, id_cliente);

-- Índices para consultas frecuentes
CREATE INDEX IF NOT EXISTS idx_buys_cliente ON buys(id_cliente);
CREATE INDEX IF NOT EXISTS idx_buys_fecha ON buys(fecha_compra);
CREATE INDEX IF NOT EXISTS idx_sale_detais_venta ON sale_detais(id_venta);
CREATE INDEX IF NOT EXISTS idx_sale_detais_isbn ON sale_detais(isbn_libro);
CREATE INDEX IF NOT EXISTS idx_reviews_cliente ON product_reviews(id_cliente);
CREATE INDEX IF NOT EXISTS idx_reviews_isbn ON product_reviews(isbn_libro);
CREATE INDEX IF NOT EXISTS idx_cart_cliente ON shopping_carts(id_cliente);
CREATE INDEX IF NOT EXISTS idx_cart_items_carrito ON cart_items(id_carrito);

COMMIT;
